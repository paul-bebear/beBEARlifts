import * as fs from "fs";
import * as os from "os";
import * as path from "path";
import * as crypto from "crypto";
import { execFileSync } from "child_process";

// Usage: npx ts-node scripts/importExerciseDemos.ts [library root]
// Needs ffmpeg, ffprobe and cwebp on PATH. Reads scripts/exerciseDemos/sources.json and writes
// images/exercises/demo/<key>.webp, src/models/exerciseDemoMedia.ts and scripts/exerciseDemos/manifest.json.

const ROOT = path.resolve(__dirname, "..");
const DEFAULT_LIBRARY = path.join(
  os.homedir(),
  "Downloads",
  "CODEX Purchase Backup 2026-10-23",
  "1.300 Animações de Treinos"
);
const OUT_DIR = path.join(ROOT, "images", "exercises", "demo");
const MEDIA_TS = path.join(ROOT, "src", "models", "exerciseDemoMedia.ts");
const MANIFEST = path.join(ROOT, "scripts", "exerciseDemos", "manifest.json");
const FRAME_SIZE = 360;
const COLUMNS = 4;
const WEBP_QUALITY = 75;

interface ISources {
  library: Record<string, unknown>;
  picks: Record<string, { source: string; review: string }>;
  missing: Record<string, string>;
}

function walk(dir: string, found: Map<string, string>, root: string): void {
  for (const name of fs.readdirSync(dir)) {
    const full = path.join(dir, name);
    if (fs.statSync(full).isDirectory()) {
      walk(full, found, root);
    } else {
      // macOS keeps the extracted Portuguese names decomposed (NFD), sources.json is written composed (NFC).
      found.set(path.relative(root, full).normalize("NFC"), full);
    }
  }
}

function frameDurationsMs(file: string): number[] {
  const out = execFileSync(
    "ffprobe",
    ["-v", "error", "-select_streams", "v", "-show_entries", "frame=duration_time", "-of", "csv=p=0", file],
    { encoding: "utf8" }
  );
  return out
    .split("\n")
    .map((l) => l.trim())
    .filter((l) => l !== "")
    .map((l) => Math.round(Number(l) * 1000));
}

function dimensions(file: string): { width: number; height: number } {
  const out = execFileSync(
    "ffprobe",
    ["-v", "error", "-select_streams", "v", "-show_entries", "stream=width,height", "-of", "csv=p=0", file],
    { encoding: "utf8" }
  ).trim();
  const [width, height] = out.split(",").map(Number);
  return { width, height };
}

function main(): void {
  const library = process.argv[2] ?? DEFAULT_LIBRARY;
  const sources: ISources = JSON.parse(
    fs.readFileSync(path.join(ROOT, "scripts", "exerciseDemos", "sources.json"), "utf8")
  );
  const files = new Map<string, string>();
  walk(library, files, library);
  fs.mkdirSync(OUT_DIR, { recursive: true });
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "exercise-demos-"));

  const media: Record<string, { frames: number; columns: number; frameMs: number[]; bytes: number }> = {};
  const imported: Record<string, unknown> = {};
  for (const key of Object.keys(sources.picks).sort()) {
    const pick = sources.picks[key];
    const file = files.get(pick.source.normalize("NFC"));
    if (file == null) {
      throw new Error(`${key}: ${pick.source} is not in ${library}`);
    }
    const frameMs = frameDurationsMs(file);
    const rows = Math.ceil(frameMs.length / COLUMNS);
    const png = path.join(tmp, `${key}.png`);
    const output = path.join(OUT_DIR, `${key}.webp`);
    execFileSync("ffmpeg", [
      "-v",
      "error",
      "-y",
      "-i",
      file,
      "-vf",
      `scale=${FRAME_SIZE}:${FRAME_SIZE}:flags=lanczos,tile=${COLUMNS}x${rows}:color=white`,
      "-frames:v",
      "1",
      png,
    ]);
    execFileSync("cwebp", ["-quiet", "-q", `${WEBP_QUALITY}`, "-m", "6", png, "-o", output]);
    const sourceBytes = fs.statSync(file).size;
    const bytes = fs.statSync(output).size;
    media[key] = { frames: frameMs.length, columns: COLUMNS, frameMs, bytes };
    imported[key] = {
      source: pick.source,
      sha256: crypto.createHash("sha256").update(fs.readFileSync(file)).digest("hex"),
      sourceBytes,
      sourceSize: dimensions(file),
      output: path.relative(ROOT, output),
      outputBytes: bytes,
      outputFrameSize: FRAME_SIZE,
      frames: frameMs.length,
      durationMs: frameMs.reduce((a, b) => a + b, 0),
      review: pick.review,
    };
    console.log(`${key}: ${sourceBytes} -> ${bytes} bytes`);
  }
  fs.rmSync(tmp, { recursive: true, force: true });

  const lines = Object.keys(media).map(
    (key) =>
      `  ${key}: { frames: ${media[key].frames}, columns: ${media[key].columns}, frameMs: [${media[key].frameMs.join(", ")}], bytes: ${media[key].bytes} },`
  );
  fs.writeFileSync(
    MEDIA_TS,
    [
      "// Generated by scripts/importExerciseDemos.ts from scripts/exerciseDemos/sources.json. Do not edit.",
      'import type { IExerciseDemoMedia } from "./exerciseDemos";',
      "",
      "export const ExerciseDemoMedia_byKey: Readonly<Record<string, IExerciseDemoMedia>> = {",
      ...lines,
      "};",
      "",
    ].join("\n")
  );
  execFileSync("npx", ["prettier", "--write", MEDIA_TS], { cwd: ROOT });
  fs.writeFileSync(
    MANIFEST,
    JSON.stringify(
      {
        generatedBy: "scripts/importExerciseDemos.ts",
        library: sources.library,
        settings: { frameSize: FRAME_SIZE, columns: COLUMNS, format: "webp", quality: WEBP_QUALITY },
        imported,
        missing: sources.missing,
      },
      null,
      2
    ) + "\n"
  );
}

main();
